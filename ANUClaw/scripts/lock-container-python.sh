#!/usr/bin/env bash
# Resolve container/python/core.in INSIDE a Linux CPython 3.12 container of the target architecture (so environment markers such as
# platform_system == "Linux" are evaluated for the TARGET — resolving on macOS silently drops Linux-only dependencies; that bug broke the first lock),
# wheels only, and write container/python/core.lock.txt with EXACT versions and the SHA-256 of every wheel from the index metadata.
# torch comes from the PyTorch CPU index (the image has no GPU; the default aarch64 wheel pulls the CUDA toolkit). Exact pins + --require-hashes keep a
# same-named package on the other index from being substituted. Regenerate for amd64 with PLATFORM=linux/amd64.
set -euo pipefail
cd "$(dirname "$0")/.."
PLATFORM=${PLATFORM:-linux/arm64}; W=$(mktemp -d)
docker run --rm --platform "$PLATFORM" -v "$PWD/container/python:/in:ro" -v "$W:/out" python:3.12-slim bash -c '
  pip --version >&2
  pip install --dry-run --quiet --no-input --only-binary=:all: --extra-index-url https://download.pytorch.org/whl/cpu --report /out/report.json -r /in/core.in'
python3 - "$W/report.json" > container/python/core.lock.txt <<'PYEOF'
import json, sys
rep = json.load(open(sys.argv[1]))
print("# GENERATED by scripts/lock-container-python.sh inside python:3.12 (linux target markers), wheels only. Do not edit.")
rows = {}
for it in rep["install"]:
    m = it["metadata"]; di = it["download_info"]; ai = di["archive_info"]; h = ai["hashes"]["sha256"] if "hashes" in ai else ai["hash"].split("=", 1)[1]
    rows[m["name"].lower().replace("_", "-")] = (m["name"], m["version"], h)
for k in sorted(rows):
    n, v, h = rows[k]; print(f"{n}=={v} --hash=sha256:{h}")
PYEOF
echo "locked $(grep -c '==' container/python/core.lock.txt) distributions; CUDA packages in lock: $(grep -ciE '^(nvidia|cuda)' container/python/core.lock.txt)"
